import React, { useEffect, useState } from "react";
import {
  Box,
  Typography,
  Card,
  CardContent,
  Table,
  TableBody,
  TableCell,
  TableContainer,
  TableHead,
  TableRow,
  Paper,
  CircularProgress,
  Alert,
  TextField,
} from "@mui/material";
import TablePagination from "@mui/material/TablePagination";
import { Search } from "@mui/icons-material";
import { adminAPI } from "../../services/api";

const WhiteLabelReports = () => {
  const [reports, setReports] = useState([]);
  const [total, setTotal] = useState(0);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [searchTerm, setSearchTerm] = useState("");
  const [debouncedSearch, setDebouncedSearch] = useState("");
  const [page, setPage] = useState(0); // MUI TablePagination is 0-indexed
  const rowsPerPage = 20;

  useEffect(() => {
    const timer = setTimeout(() => setDebouncedSearch(searchTerm), 600);
    return () => clearTimeout(timer);
  }, [searchTerm]);

  useEffect(() => {
    const load = async () => {
      try {
        setLoading(true);
        setError("");
        const res = await adminAPI.getWhiteLabelReports({
          page: page + 1,
          limit: rowsPerPage,
          search: debouncedSearch,
        });
        setReports(res.data.reports || []);
        setTotal(res.data.total || 0);
      } catch (err) {
        console.error("Failed to load White Labeled reports:", err);
        setError("Failed to load White Labeled Reports.");
      } finally {
        setLoading(false);
      }
    };
    load();
  }, [page, debouncedSearch]);

  return (
    <Box>
      <Typography variant="h4" gutterBottom>
        White Labeled Reports
      </Typography>

      {error && (
        <Alert severity="error" sx={{ mb: 2 }}>
          {error}
        </Alert>
      )}

      <Card sx={{ mt: 3, boxShadow: 3, borderRadius: 2 }}>
        <CardContent>
          <Typography variant="h6" gutterBottom>
            Reports generated by White Labeled partners
          </Typography>

          <TextField
            fullWidth
            sx={{ mb: 3 }}
            label="Search by partner, franchise, or report name"
            value={searchTerm}
            onChange={(e) => {
              setSearchTerm(e.target.value);
              setPage(0);
            }}
            InputProps={{ endAdornment: <Search /> }}
          />

          {loading ? (
            <Box sx={{ display: "flex", justifyContent: "center", py: 4 }}>
              <CircularProgress />
            </Box>
          ) : reports.length === 0 ? (
            <Typography sx={{ textAlign: "center", py: 4 }}>
              {debouncedSearch
                ? "No reports match your search."
                : "No white labeled reports generated yet."}
            </Typography>
          ) : (
            <TableContainer component={Paper}>
              <Table sx={{ minWidth: 800 }} aria-label="white labeled reports table">
                <TableHead>
                  <TableRow>
                    <TableCell>Report Name</TableCell>
                    <TableCell>Partner</TableCell>
                    <TableCell>Franchise ID</TableCell>
                    <TableCell>Customer</TableCell>
                    <TableCell>Generated On</TableCell>
                  </TableRow>
                </TableHead>
                <TableBody>
                  {reports.map((r) => (
                    <TableRow key={r._id} sx={{ "&:last-child td": { border: 0 } }}>
                      <TableCell>{r.name || "N/A"}</TableCell>
                      <TableCell>{r.partnerName || "N/A"}</TableCell>
                      <TableCell sx={{ fontFamily: "monospace" }}>
                        {r.franchiseCode || "N/A"}
                      </TableCell>
                      <TableCell>{r.customerName || "N/A"}</TableCell>
                      <TableCell sx={{ whiteSpace: "nowrap" }}>
                        {r.createdAt ? new Date(r.createdAt).toLocaleDateString("en-IN") : "N/A"}
                      </TableCell>
                    </TableRow>
                  ))}
                </TableBody>
              </Table>
              <TablePagination
                component="div"
                count={total}
                page={page}
                rowsPerPage={rowsPerPage}
                rowsPerPageOptions={[rowsPerPage]}
                onPageChange={(_, newPage) => setPage(newPage)}
              />
            </TableContainer>
          )}
        </CardContent>
      </Card>
    </Box>
  );
};

export default WhiteLabelReports;
