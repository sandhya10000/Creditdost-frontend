import React, { useEffect, useState } from "react";
import {
  Box,
  Typography,
  Table,
  TableBody,
  TableCell,
  TableContainer,
  TableHead,
  TableRow,
} from "@mui/material";
import { adminAPI } from "../../services/api";
import {
  CardAlerts,
  CellText,
  DateCell,
  EmptyRow,
  LoadingBar,
  SearchField,
  SectionCard,
  TableFooter,
  TableToolbar,
} from "./ui/AdminTable";
import { bodyRowSx, headRowSx } from "./ui/tableStyles";

const WhiteLabelReports = ({ embedded = false }) => {
  const [reports, setReports] = useState([]);
  const [total, setTotal] = useState(0);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [searchTerm, setSearchTerm] = useState("");
  const [debouncedSearch, setDebouncedSearch] = useState("");
  const [page, setPage] = useState(1);
  const rowsPerPage = 20;

  useEffect(() => {
    const timer = setTimeout(() => setDebouncedSearch(searchTerm), 600);
    return () => clearTimeout(timer);
  }, [searchTerm]);

  useEffect(() => {
    const load = async () => {
      try {
        setLoading(true);
        setError("");
        const res = await adminAPI.getWhiteLabelReports({
          page,
          limit: rowsPerPage,
          search: debouncedSearch,
        });
        setReports(res.data.reports || []);
        setTotal(res.data.total || 0);
      } catch (err) {
        console.error("Failed to load White Labeled reports:", err);
        setError("Failed to load White Labeled Reports.");
      } finally {
        setLoading(false);
      }
    };
    load();
  }, [page, debouncedSearch]);

  return (
    <Box>
      {!embedded && (
        <Typography variant="h4" gutterBottom>
          White Labeled Reports
        </Typography>
      )}

      <SectionCard>
        <TableToolbar>
          <SearchField
            value={searchTerm}
            onChange={(value) => {
              setSearchTerm(value);
              setPage(1);
            }}
            placeholder="Search by partner, franchise or report name"
          />
          <Typography variant="body2" color="text.secondary">
            Reports generated by White Labeled partners
          </Typography>
        </TableToolbar>

        <CardAlerts error={error} onCloseError={() => setError("")} />
        <LoadingBar loading={loading} />

        <TableContainer>
          <Table size="small" sx={{ minWidth: 800 }} aria-label="white labeled reports table">
            <TableHead>
              <TableRow sx={headRowSx}>
                <TableCell>Report</TableCell>
                <TableCell>Partner</TableCell>
                <TableCell>Customer</TableCell>
                <TableCell>Generated On</TableCell>
              </TableRow>
            </TableHead>
            <TableBody>
              {reports.length === 0 ? (
                <EmptyRow
                  colSpan={4}
                  loading={loading}
                  title={debouncedSearch ? "No reports match your search" : "No reports yet"}
                  hint={
                    debouncedSearch
                      ? "Try a different search term."
                      : "White labeled reports appear here once partners generate them."
                  }
                />
              ) : (
                reports.map((r) => (
                  <TableRow key={r._id} hover sx={bodyRowSx}>
                    <TableCell sx={{ maxWidth: 280 }}>
                      <CellText variant="body2" fontWeight={600}>
                        {r.name || "N/A"}
                      </CellText>
                    </TableCell>
                    <TableCell sx={{ maxWidth: 240 }}>
                      <CellText variant="body2">{r.partnerName || "N/A"}</CellText>
                      <Typography variant="caption" color="primary.main" fontWeight={600}>
                        {r.franchiseCode || "No partner ID"}
                      </Typography>
                    </TableCell>
                    <TableCell sx={{ maxWidth: 220 }}>
                      <CellText variant="body2">{r.customerName || "N/A"}</CellText>
                    </TableCell>
                    <TableCell>
                      <DateCell value={r.createdAt} />
                    </TableCell>
                  </TableRow>
                ))
              )}
            </TableBody>
          </Table>
        </TableContainer>

        <TableFooter page={page} rowsPerPage={rowsPerPage} total={total} onPageChange={setPage} />
      </SectionCard>
    </Box>
  );
};

export default WhiteLabelReports;
